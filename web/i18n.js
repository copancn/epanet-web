let LANG = 'zh';
try {
  const stored = localStorage.getItem('epanet-web-lang');
  if (stored === 'zh' || stored === 'en') LANG = stored;
  else if (navigator.language && !/^zh/i.test(navigator.language)) LANG = 'en';
} catch (e) {}

function t(key, ...args) {
  const dict = I18N[LANG] || I18N.zh;
  let s = dict[key] !== undefined ? dict[key] : (I18N.zh[key] !== undefined ? I18N.zh[key] : key);
  if (args.length) s = s.replace(/\{(\d+)\}/g, (m, i) => (args[i] !== undefined ? args[i] : m));
  return s;
}

function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
  document.title = t('app.title');
  document.documentElement.lang = LANG === 'zh' ? 'zh-CN' : 'en';
}

function setLang(lang) {
  LANG = lang === 'en' ? 'en' : 'zh';
  try { localStorage.setItem('epanet-web-lang', LANG); } catch (e) {}
  applyI18n();
  document.dispatchEvent(new CustomEvent('langchange', { detail: { lang: LANG } }));
}

